// Generates src/api/generated.ts from api/openapi.json (the backend's /openapi.json).
// Usage: node scripts/gen-api.mjs [path-or-url]   (default: api/openapi.json)
import { readFileSync, writeFileSync } from "node:fs"

const src = process.argv[2] ?? "api/openapi.json"
const spec = src.startsWith("http")
  ? await (await fetch(src)).json()
  : JSON.parse(readFileSync(src, "utf8"))
const schemas = spec.components?.schemas ?? {}

function ts(s) {
  if (!s) return "unknown"
  if (s.$ref) return s.$ref.split("/").pop()
  if (s.anyOf) return s.anyOf.map(ts).join(" | ")
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ")
  switch (s.type) {
    case "string":
      return "string"
    case "integer":
    case "number":
      return "number"
    case "boolean":
      return "boolean"
    case "null":
      return "null"
    case "array":
      return `${ts(s.items)}[]`
    case "object":
      if (s.properties) return obj(s)
      return "Record<string, unknown>"
    default:
      return "unknown"
  }
}
function obj(s) {
  const req = new Set(s.required ?? [])
  const props = Object.entries(s.properties ?? {}).map(
    ([k, v]) => `  ${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(v)}`,
  )
  return `{\n${props.join("\n")}\n}`
}

let out = `// GENERATED by scripts/gen-api.mjs from ${spec.info?.title} ${spec.info?.version} OpenAPI. Do not edit by hand.\n// Note: the backend declares most responses as untyped objects, so response shapes live in types.ts and are\n// checked at runtime by normalize.ts.\n\n`
for (const [name, s] of Object.entries(schemas))
  out += `export interface ${name} ${obj(s)}\n\n`

const ops = []
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    const params = (op.parameters ?? []).filter(
      (p) => p.name !== "authorization",
    )
    const q = params.filter((p) => p.in === "query")
    const pp = params.filter((p) => p.in === "path")
    const body = op.requestBody?.content?.["application/json"]?.schema
    const okCode = Object.keys(op.responses ?? {}).find((c) =>
      c.startsWith("2"),
    )
    const res = op.responses?.[okCode]?.content?.["application/json"]?.schema
    ops.push(
      `  ${JSON.stringify(`${method.toUpperCase()} ${path}`)}: {\n    path: ${
        pp.length
          ? obj({
              properties: Object.fromEntries(pp.map((p) => [p.name, p.schema])),
              required: pp.map((p) => p.name),
            }).replace(/\n/g, "\n    ")
          : "never"
      }\n    query: ${
        q.length
          ? obj({
              properties: Object.fromEntries(q.map((p) => [p.name, p.schema])),
            }).replace(/\n/g, "\n    ")
          : "never"
      }\n    body: ${
        body ? ts(body).replace(/\n/g, "\n    ") : "never"
      }\n    response: ${ts(res).replace(/\n/g, "\n    ")}\n  }`,
    )
  }
}
out += `export interface Paths {\n${ops.join("\n")}\n}\n\nexport type Route = keyof Paths\n`
writeFileSync("src/api/generated.ts", out)
console.log(`wrote src/api/generated.ts (${ops.length} operations)`)
